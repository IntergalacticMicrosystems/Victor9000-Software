"""Generate font.inc for the Victor 9000 RAM test ROM.

ASCII-indexed font: glyph index = ASCII - 0x20, covering 0x20..0x5F (64 glyphs).
Each glyph is 16 words (32 bytes). A 5-wide x 7-tall cell is placed at columns
2..6 (bits 6..2) and glyph rows 4..10; the rest is blank. This matches the
Victor cell convention (column c -> bit (8-c); visible width ~10px, bits 0-9).
"""

FIRST = 0x20
LAST = 0x5F
COL_SHIFT = 2          # 5-wide glyph occupies bits 6..2 (cols 2..6 of 9)
ROW_OFFSET = 4         # 7 rows placed at glyph rows 4..10

