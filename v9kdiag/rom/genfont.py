def glyph_words(art):
    words = [0] * 16
    if art:
        for r, row in enumerate(art):
            w = 0
            for c, px in enumerate(row):
                if px in ('#', '1'):
                    # Victor hardware scans font bits low->high as left->right,
                    # so column c maps to bit (c + COL_SHIFT) (not 8 - ...).
                    w |= 1 << (c + COL_SHIFT)
            words[ROW_OFFSET + r] = w
    return words


def main():
    out = []
    out.append("; font.inc - ASCII-indexed font for the Victor 9000 RAM test ROM")
    out.append("; GENERATED by genfont.py - do not edit by hand.")
    out.append("; Glyph index = ASCII - 0x20 (covers 0x20..0x5F). 16 words/glyph.")
    n_ascii = LAST - FIRST + 1
    out.append("FONT_FIRST_ASCII equ 0%02Xh" % FIRST)
    out.append("FONT_LAST_ASCII  equ 0%02Xh" % LAST)
    out.append("FONT_GLYPHS equ %d" % n_ascii)
    out.append("font_data:")
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        art = G.get(ch)
        words = glyph_words(art)
        label = ch if ch != ' ' else 'space'
        out.append("  ; 0x%02X '%s'" % (code, label))
        for w in words:
            out.append("    dw 0%04Xh" % w)
    open("font.inc", "w").write("\n".join(out) + "\n")
    print("wrote font.inc:", n_ascii, "glyphs")


if __name__ == "__main__":
    main()
